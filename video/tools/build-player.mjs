// Build the data file for the episode player (video/index.html).
// Usage: node build-player.mjs [outputDir]   → writes ../player-data.js
//
// Sources:
//   ../scripts/<base>.md   scene titles and step narration ("**[s.k]** text")
//   <outputDir>/<base>.srt caption timings from the renderer (optional; default ../output)
// SRT cues are sentences of the steps in order, so each cue is matched to its step by walking
// the narration text. Episodes without an SRT keep the script text but have no timestamps.
// The data is a plain <script> file so the player works from file:// without fetch.
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.join(here, '..');
const outDir = path.resolve(process.argv[2] || path.join(root, 'output'));
const GROUP = { E: '主线', B: '下篇一 · 幕后核心', P: '下篇二 · 产品深潜' };

const norm = s => s.replace(/[\s，。！？；：、,.!?;:“”"'‘’（）()《》【】\[\]「」—…·-]/g, '');
const secs = s => { const [h, m, r] = s.split(':'); return +h * 3600 + +m * 60 + parseFloat(r.replace(',', '.')); };

function parseScript(md) {
  const title = (md.match(/^# \S+ (.+)$/m) || [])[1] || '';
  const scenes = [];
  for (const line of md.split('\n')) {
    let m = line.match(/^## 场景 (\d+)：(.+)$/);
    if (m) { scenes.push({ title: m[2].trim(), steps: [] }); continue; }
    m = line.match(/^\*\*\[(\d+)\.(\d+)\]\*\* (.+)$/);
    if (m && scenes.length) scenes[scenes.length - 1].steps[+m[2]] = m[3].trim();
  }
  scenes.forEach(s => { s.steps = Array.from(s.steps, x => x || ''); });
  return { title, scenes };
}

function parseSrt(txt) {
  return txt.replace(/\r/g, '').trim().split(/\n\n+/).map(b => {
    const L = b.split('\n'), m = (L[1] || '').match(/(\S+) --> (\S+)/);
    return m && { t: secs(m[1]), e: secs(m[2]), text: L.slice(2).join(' ').trim() };
  }).filter(Boolean);
}

// Assign each cue to the step whose normalized text contains it, walking forward.
function align(scenes, cues) {
  const flat = [];
  let full = '';
  scenes.forEach((s, si) => s.steps.forEach((txt, st) => { flat.push({ si, st, from: full.length }); full += norm(txt); }));
  const stepAt = pos => { let k = 0; while (k + 1 < flat.length && flat[k + 1].from <= pos) k++; return flat[k]; };
  let cur = 0, missed = 0, last = flat[0];
  const lines = scenes.map(() => []);
  for (const c of cues) {
    const n = norm(c.text);
    const i = n ? full.indexOf(n, cur) : -1;
    if (i >= 0) { last = stepAt(i); cur = i + n.length; } else missed++;
    lines[last.si].push([+c.t.toFixed(2), c.text, last.st]);
  }
  return { lines, missed };
}

const files = fs.readdirSync(path.join(root, 'scripts')).filter(f => /^(EP\d\d|B\d\d|P\d\d)-.+\.md$/.test(f)).sort((a, b) => {
  const o = f => 'EBP'.indexOf(f[0]);
  return o(a) - o(b) || a.localeCompare(b);
});

// Knowledge docs per episode, from the "来源" column of ../README.md:
// "02（…）" / "11、12" → chapters/NN-*.md; "backstage/B01" / "products/P01" → that folder's file.
const repo = path.join(root, '..');
const docTitle = rel => (fs.readFileSync(path.join(repo, rel), 'utf8').match(/^# (.+)$/m) || [])[1] || rel;
const findDoc = (dir, prefix) => {
  const f = fs.readdirSync(path.join(repo, dir)).find(x => x.startsWith(prefix + '-') && x.endsWith('.md'));
  return f && `${dir}/${f}`;
};
const DOCS = {};
for (const line of fs.readFileSync(path.join(root, 'README.md'), 'utf8').split('\n')) {
  const cols = line.split('|').map(s => s.trim());
  if (!/^(EP|B|P)\d\d$/.test(cols[1] || '')) continue;
  const src = cols[3].replace(/（.*?）/g, '');
  const m = src.match(/^(backstage|products)\/([BP]\d\d)$/);
  const rels = m ? [findDoc(m[1], m[2])] : (src.match(/\d\d/g) || []).map(n => findDoc('chapters', n));
  DOCS[cols[1]] = rels.filter(Boolean).map(rel => ({ href: '../' + rel, title: docTitle(rel) }));
}

const eps = [], report = [];
const groupIndex = {};
for (const f of files) {
  const base = f.replace(/\.md$/, ''), id = base.split('-')[0], g = id[0];
  const { title, scenes } = parseScript(fs.readFileSync(path.join(root, 'scripts', f), 'utf8'));
  const srtPath = path.join(outDir, base + '.srt');
  let sc, dur = 0, timed = false;
  if (fs.existsSync(srtPath)) {
    const cues = parseSrt(fs.readFileSync(srtPath, 'utf8'));
    const { lines, missed } = align(scenes, cues);
    dur = cues.length ? +cues[cues.length - 1].e.toFixed(1) : 0;
    sc = scenes.map((s, si) => [s.title, lines[si].length ? lines[si][0][0] : null, lines[si]]);
    timed = true;
    report.push(`${id}: ${cues.length} cues${missed ? `, ${missed} unmatched` : ''}`);
  } else {
    sc = scenes.map(s => [s.title, null, s.steps.map((txt, st) => [null, txt, st])]);
    report.push(`${id}: no SRT, script only`);
  }
  groupIndex[g] = (groupIndex[g] || 0) + 1;
  if (!DOCS[id] || !DOCS[id].length) report.push(`${id}: no knowledge doc found`);
  eps.push({ id, base, title, g, p: groupIndex[g], timed, dur, docs: DOCS[id] || [], sc });
}

const out = `// Generated by video/tools/build-player.mjs — do not edit by hand.\nconst GROUPS=${JSON.stringify(GROUP)};\nconst EPS=${JSON.stringify(eps)};\n`;
fs.writeFileSync(path.join(root, 'player-data.js'), out);

// Bundle knowledge Markdown files into docs-data.js so video/index.html can render them over file:// without fetch.
const docMap = {};
for (const dir of ['chapters', 'backstage', 'products']) {
  const fullDir = path.join(repo, dir);
  if (!fs.existsSync(fullDir)) continue;
  for (const f of fs.readdirSync(fullDir).filter(x => x.endsWith('.md')).sort()) {
    const rel = `../${dir}/${f}`;
    docMap[rel] = fs.readFileSync(path.join(fullDir, f), 'utf8');
  }
}
for (const top of ['README.md', 'WRITING-GUIDE.md']) {
  const p = path.join(repo, top);
  if (fs.existsSync(p)) docMap[`../${top}`] = fs.readFileSync(p, 'utf8');
}
const docsOut = `// Generated by video/tools/build-player.mjs — do not edit by hand.\nconst DOC_MD=${JSON.stringify(docMap)};\n`;
fs.writeFileSync(path.join(root, 'docs-data.js'), docsOut);

console.log(report.join('\n'));
console.log(`wrote player-data.js: ${eps.length} episodes, ${(out.length / 1024).toFixed(0)} KB`);
console.log(`wrote docs-data.js: ${Object.keys(docMap).length} docs, ${(docsOut.length / 1024).toFixed(0)} KB`);
